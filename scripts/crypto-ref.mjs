function generateFixtures() {
  const c = new Cryptor(SECRET)

  const encrypt = ['s3cr3t-p@ss', 'пароль-密码-🔑', 'y'.repeat(4096)].map(
    (plaintext, i) => ({ name: `field-${i}`, plaintext, hex: c.encrypt(plaintext) })
  )

  const encryptData = [
    { name: 'empty-vault', value: { entries: [] } },
    { name: 'nested', value: { a: 1, b: 'два', c: [true, null, 'x'] } }
  ].map(({ name, value }) => ({ name, value, blob: c.encryptData(value) }))

  const obscured = ENTRIES.map(e => c.obscure(e))
  const exposed = obscured.map(e => c.expose(e))
  const vault = {
    name: 'full-vault',
    entries: ENTRIES,
    exposed,
    blob: c.encryptData({ entries: obscured })
  }

  return {
    note: 'Golden fixtures generated by scripts/crypto-ref.mjs. Regenerate with `node scripts/crypto-ref.mjs gen-fixtures`.',
    secret: SECRET,
    hashSecret: [{ password: PASSWORD, secret: SECRET }],
    encrypt,
    encryptData,
    vault
  }
}

// ---- CLI ------------------------------------------------------------------

function main() {
  const [cmd, ...args] = process.argv.slice(2)
  switch (cmd) {
    case 'hash-secret':
      process.stdout.write(hashSecret(args[0]))
      break
    case 'encrypt':
      process.stdout.write(new Cryptor(args[0]).encrypt(args[1]))
      break
    case 'decrypt':
      process.stdout.write(new Cryptor(args[0]).decrypt(args[1]))
      break
    case 'encrypt-data':
      process.stdout.write(new Cryptor(args[0]).encryptData(JSON.parse(args[1])))
      break
    case 'decrypt-data':
      process.stdout.write(JSON.stringify(new Cryptor(args[0]).decryptData(args[1])))
      break
    case 'gen-fixtures': {
      const __dirname = path.dirname(fileURLToPath(import.meta.url))
      const out = path.resolve(__dirname, '../src-tauri/tests/fixtures/fixtures.json')
      fs.mkdirSync(path.dirname(out), { recursive: true })
      fs.writeFileSync(out, JSON.stringify(generateFixtures(), null, 2) + '\n')
      process.stdout.write(`wrote ${out}\n`)
      break
    }
    default:
      process.stderr.write(
        'usage: crypto-ref.mjs <hash-secret|encrypt|decrypt|encrypt-data|decrypt-data|gen-fixtures> [args]\n'
      )
      process.exit(1)
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main()
}
