#!/usr/bin/env node
// Reference implementation of the legacy @swiftyapp/cryptor vault format, using
// only Node's built-in `crypto`. Mirrors legacy/src/main/application/cryptor/index.js.
// Used to generate golden fixtures and to cross-check the Rust implementation.
//
// Format: hex( salt[64] ‖ iv[16] ‖ tag[16] ‖ ciphertext ), AES-256-GCM,
// key = PBKDF2-HMAC-SHA512(secret, salt, 100000, 32). Whole-object blobs are
// base64(hex). Secret = base64(SHA512(password)).

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SALT_LEN = 64
const IV_LEN = 16
const TAG_LEN = 16
const ITERATIONS = 100000
const KEY_LEN = 32

const SENSITIVE_FIELDS = {
  login: ['password', 'otp'],
  note: ['note'],
  card: ['pin']
}

export const hashSecret = value =>
  crypto.createHash('sha512').update(value).digest('base64')

export class Cryptor {
  constructor(secret) {
    this.secret = secret
  }

  encrypt(data) {
    const salt = crypto.randomBytes(SALT_LEN)
    const iv = crypto.randomBytes(IV_LEN)
    const key = crypto.pbkdf2Sync(this.secret, salt, ITERATIONS, KEY_LEN, 'sha512')
    const cipher = crypto.createCipheriv('aes-256-gcm', key, iv)
    const ciphertext = Buffer.concat([cipher.update(data, 'utf8'), cipher.final()])
    const tag = cipher.getAuthTag()
    return Buffer.concat([salt, iv, tag, ciphertext]).toString('hex')
  }

  decrypt(data) {
    const buf = Buffer.from(data, 'hex')
    const salt = buf.subarray(0, SALT_LEN)
    const iv = buf.subarray(SALT_LEN, SALT_LEN + IV_LEN)
    const tag = buf.subarray(SALT_LEN + IV_LEN, SALT_LEN + IV_LEN + TAG_LEN)
    const ciphertext = buf.subarray(SALT_LEN + IV_LEN + TAG_LEN)
    const key = crypto.pbkdf2Sync(this.secret, salt, ITERATIONS, KEY_LEN, 'sha512')
    const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv)
    decipher.setAuthTag(tag)
    return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString('utf8')
  }

  encryptData(data) {
    return Buffer.from(this.encrypt(JSON.stringify(data)), 'utf8').toString('base64')
  }

  decryptData(encrypted) {
    return JSON.parse(this.decrypt(Buffer.from(encrypted, 'base64').toString('utf8')))
  }

  #prepare(entry, callback) {
    const object = Object.assign({}, entry)
    ;(SENSITIVE_FIELDS[object.type] || []).forEach(field => {
      object[field] = !object[field] ? '' : callback(object[field])
    })
    return object
  }

  obscure(entry) {
    return this.#prepare(entry, v => this.encrypt(v))
  }

  expose(entry) {
    return this.#prepare(entry, v => this.decrypt(v))
  }
}

